#!/usr/bin/env python3
"""Generate full-world scoring configs for trained round_4 runs.

The training configs set `inference.labeled_only: true`, which is why a training
run scores only its 29,734 split-assigned rows. For the website we need every
candidate scored: the r4 candidates dir already holds ~154,670 rows across 165
country CSVs, and `data.countries` is empty, which makes _load_candidates_csv load
all of them. So a scoring config is the training config plus:

  inference.labeled_only : false                     -- score the whole world
  inference.checkpoint   : <run>/best_model.pt       -- reuse the trained weights
  inference.norm_stats_stem : <run>                  -- MUST match the training run,
                                                        or every score is computed
                                                        under the wrong normalisation
"""
from __future__ import annotations

import argparse
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
CFG = REPO / "configs" / "rachel_clusters"


def make(run: str, force: bool = False) -> Path | None:
    src = CFG / f"{run}.yaml"
    if not src.exists():
        print(f"  ! no training config for {run}"); return None
    out = CFG / f"{run}_score.yaml"
    if out.exists() and not force:
        return out
    cfg = yaml.safe_load(src.read_text())
    cfg["run_name"] = f"{run}_score"
    # Score EVERY row, including labels with no slot in the taxonomy
    # (Farm: Unknown/Mixed/Other/PigsOrPoultry, Ambiguous). The training
    # candidates dir drops those 2,597 rows, which silently shipped 18 datasets
    # missing 2,574 predictions and under-covered every evaluation slice.
    # keep_unscorable_labels keeps them as label=-1 (scored, never trained on),
    # matching how every historical *_scoreall release was built.
    data = cfg.setdefault("data", {})
    data["keep_unscorable_labels"] = True
    data["candidates_dir"] = "data/rachel_geometry_candidates/candidates_world_v10_r4_scoreall"
    inf = cfg.setdefault("inference", {})
    inf["labeled_only"] = False
    inf["checkpoint"] = f"data/output/{run}/best_model.pt"
    inf["norm_stats_stem"] = run
    inf.setdefault("batch_size", 256)
    inf.setdefault("num_workers", 8)
    inf.setdefault("mixed_precision", True)
    header = (f"# Full-world scoring config for {run} (generated by gen_score_configs.py).\n"
              f"# Scores every candidate, not just split-assigned rows, for website publication.\n")
    out.write_text(header + yaml.safe_dump(cfg, sort_keys=False))
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", nargs="*", help="run names (default: all collected)")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()

    runs = args.runs
    if not runs:
        gpu = REPO / "experiments" / "gpu_results"
        runs = sorted(d.name for d in gpu.glob("world_v10_fourclass_r4_*")
                      if (d / "scored_candidates.parquet").exists()
                      and not d.name.endswith("_score"))   # never double-suffix
    print(f"generating scoring configs for {len(runs)} run(s)")
    made = [make(r, args.force) for r in runs]
    made = [m for m in made if m]
    for m in made:
        print("  ", m.name)

    # Validate: config loads, and the startup script the launcher would send is
    # syntactically valid bash (a malformed one killed four pods earlier).
    import subprocess, sys, tempfile
    sys.path.insert(0, str(REPO))
    from training.config import load_config
    from training import runpod_launch as R
    bad = 0
    for m in made:
        rel = f"configs/rachel_clusters/{m.name}"
        try:
            c = load_config(rel)
            script = R._build_startup_script(c, rel, ["inference"])
            with tempfile.NamedTemporaryFile("w", suffix=".sh", delete=False) as f:
                f.write(script); path = f.name
            p = subprocess.run(["bash", "-n", path], capture_output=True, text=True)
            if p.returncode != 0:
                print(f"  *** {m.name}: bash -n FAILED: {p.stderr[:160]}"); bad += 1
            elif c.inference.labeled_only is not False:
                print(f"  *** {m.name}: labeled_only not False"); bad += 1
            elif not getattr(c.data, "keep_unscorable_labels", False):
                print(f"  *** {m.name}: keep_unscorable_labels not True"); bad += 1
        except Exception as exc:
            print(f"  *** {m.name}: {type(exc).__name__}: {str(exc)[:160]}"); bad += 1
    print("all scoring configs valid" if not bad else f"*** {bad} INVALID ***")


if __name__ == "__main__":
    main()
